import hashlib
import json
import zipfile
from pathlib import Path
from typing import Any

import pandas as pd

from services.api.config import settings


def compute_file_sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()

def create_evidence_package(
    analysis_id: str,
    event_data: dict[str, Any],
    analysis_config: dict[str, Any],
    raster_paths: dict[str, Path],
    vector_paths: dict[str, Path],
    metrics_data: dict[str, Any],
    pdf_report_path: Path | None = None,
    output_dir: Path | None = None
) -> Path:
    """
    Assembles a complete, reproducible georeferenced flood impact evidence package.
    """
    out_dir = Path(output_dir or settings.EXPORTS_DIR)
    out_dir.mkdir(parents=True, exist_ok=True)

    zip_path = out_dir / f"flood_evidence_{analysis_id}.zip"
    temp_pkg_dir = out_dir / f"pkg_{analysis_id}"
    temp_pkg_dir.mkdir(parents=True, exist_ok=True)

    # Subdirectories
    rasters_dir = temp_pkg_dir / "rasters"
    vectors_dir = temp_pkg_dir / "vectors"
    tables_dir = temp_pkg_dir / "tables"
    metadata_dir = temp_pkg_dir / "metadata"

    for d in [rasters_dir, vectors_dir, tables_dir, metadata_dir]:
        d.mkdir(parents=True, exist_ok=True)

    # 1. Copy rasters
    for key, r_path in raster_paths.items():
        if r_path and Path(r_path).exists():
            dest = rasters_dir / f"{key}.tif"
            dest.write_bytes(Path(r_path).read_bytes())

    # 2. Copy vectors
    for key, v_path in vector_paths.items():
        if v_path and Path(v_path).exists():
            ext = Path(v_path).suffix
            dest = vectors_dir / f"{key}{ext}"
            dest.write_bytes(Path(v_path).read_bytes())

    # 3. Create tables (CSV)
    # Event summary
    summary_df = pd.DataFrame([{
        "event_id": event_data.get("id"),
        "event_name": event_data.get("name"),
        "total_water_km2": metrics_data.get("total_water_km2", 0.0),
        "preexisting_water_km2": metrics_data.get("preexisting_water_km2", 0.0),
        "newly_flooded_km2": metrics_data.get("newly_flooded_km2", 0.0),
        "receded_km2": metrics_data.get("receded_km2", 0.0),
        "affected_buildings": metrics_data.get("affected_buildings", 0),
        "affected_road_km": metrics_data.get("affected_road_km", 0.0)
    }])
    summary_df.to_csv(tables_dir / "event_summary.csv", index=False)

    # Breakdown metrics table
    if "breakdown" in metrics_data:
        breakdown_df = pd.DataFrame(metrics_data["breakdown"])
        breakdown_df.to_csv(tables_dir / "observation_metrics.csv", index=False)

    # 4. Write metadata & provenance
    (metadata_dir / "event.json").write_text(json.dumps(event_data, indent=2))
    (metadata_dir / "processing_configuration.json").write_text(json.dumps(analysis_config, indent=2))

    provenance = {
        "analysis_id": analysis_id,
        "software": "Flood Impact Assessment",
        "version": settings.VERSION,
        "dataset_attribution": "IBM, DLR, and ESA Φ-lab (ImpactMesh-Flood) / Copernicus EMS / OpenStreetMap",
        "methodology": analysis_config.get("method", "baseline"),
        "provenance_timestamp": str(pd.Timestamp.utcnow())
    }
    (metadata_dir / "provenance.json").write_text(json.dumps(provenance, indent=2))

    # 5. Include PDF report if available
    if pdf_report_path and Path(pdf_report_path).exists():
        (temp_pkg_dir / "report.pdf").write_bytes(Path(pdf_report_path).read_bytes())

    # 6. Readme
    readme_text = f"""# Flood Impact Evidence Package: {event_data.get('name', analysis_id)}

Analysis ID: {analysis_id}
Generated by: Flood Impact Assessment Platform v{settings.VERSION}

## Contents
- `report.pdf`: Comprehensive human-readable evidence report
- `rasters/`: Cloud-Optimized GeoTIFFs (permanent water, inundation extent, persistence, uncertainty)
- `vectors/`: Georeferenced GeoPackages (inundated polygons, affected buildings, affected roads)
- `tables/`: Tabular summary and impact metrics (CSV)
- `metadata/`: Provenance, configurations, and SHA-256 checksums

## Attribution
- Satellite Data: Copernicus Sentinel-1 SAR & Sentinel-2 Optical (ESA)
- Ground Truth Annotations: Copernicus Emergency Management Service (EMS)
- Datasets: ImpactMesh-Flood (IBM, DLR, ESA Φ-lab, CC BY 4.0)
- Infrastructure: OpenStreetMap Contributors (ODbL)
"""
    (temp_pkg_dir / "README.md").write_text(readme_text)

    # 7. Checksums
    checksums = {}
    for f in temp_pkg_dir.rglob("*"):
        if f.is_file():
            rel = str(f.relative_to(temp_pkg_dir))
            checksums[rel] = compute_file_sha256(f)

    with open(metadata_dir / "checksums.sha256", "w") as f:
        f.writelines(f"{chk}  {p}\n" for p, chk in sorted(checksums.items()))

    # 8. Create ZIP
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for f in temp_pkg_dir.rglob("*"):
            if f.is_file():
                zf.write(f, f.relative_to(temp_pkg_dir))

    return zip_path
